"""步骤25B：售后侧退款执行、分摊、账本与对账表；渠道流水仍归属独立模拟服务。"""

VERSION = "0020"
_SUFFIX = " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"


def statements() -> list[str]:
    return [
        "CREATE TABLE IF NOT EXISTS refund_execution ("
        " tenant_id VARCHAR(64) NOT NULL, execution_id VARCHAR(64) NOT NULL,"
        " refund_request_id VARCHAR(64) NOT NULL, order_id VARCHAR(64) NOT NULL,"
        " payment_id VARCHAR(64) NOT NULL, amount_minor BIGINT UNSIGNED NOT NULL,"
        " currency CHAR(3) NOT NULL,"
        " funds_status VARCHAR(16) NOT NULL,"
        " channel_ref VARCHAR(64) NULL, channel_transaction_ref VARCHAR(64) NULL,"
        " failure_code VARCHAR(64) NULL,"
        " idempotency_key VARCHAR(64) NOT NULL, request_digest CHAR(64) NOT NULL,"
        " environment VARCHAR(32) NOT NULL, actor_subject_id VARCHAR(64) NOT NULL,"
        " customer_id VARCHAR(64) NOT NULL,"
        " created_at DATETIME(6) NOT NULL, updated_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, execution_id),"
        " UNIQUE KEY uq_refund_execution_idem (tenant_id, idempotency_key),"
        " KEY ix_refund_execution_request (tenant_id, refund_request_id, funds_status),"
        " CONSTRAINT chk_refund_execution_amount CHECK (amount_minor > 0),"
        " CONSTRAINT chk_refund_execution_status CHECK (funds_status IN"
        " ('submitting','processing','unknown','succeeded','failed'))"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS refund_allocation ("
        " tenant_id VARCHAR(64) NOT NULL, allocation_id VARCHAR(64) NOT NULL,"
        " execution_id VARCHAR(64) NOT NULL, request_line_id VARCHAR(64) NOT NULL,"
        " payment_detail_id VARCHAR(64) NOT NULL,"
        " component VARCHAR(16) NOT NULL, amount_minor BIGINT UNSIGNED NOT NULL,"
        " environment VARCHAR(32) NOT NULL,"
        " PRIMARY KEY (tenant_id, allocation_id),"
        " UNIQUE KEY uq_refund_allocation_line (tenant_id, execution_id,"
        " request_line_id, component),"
        " KEY ix_refund_allocation_detail (tenant_id, payment_detail_id),"
        " CONSTRAINT fk_refund_allocation_execution FOREIGN KEY (tenant_id, execution_id)"
        " REFERENCES refund_execution (tenant_id, execution_id),"
        " CONSTRAINT chk_refund_allocation_amount CHECK (amount_minor > 0),"
        " CONSTRAINT chk_refund_allocation_component CHECK (component IN ('goods','shipping'))"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS refund_ledger ("
        " tenant_id VARCHAR(64) NOT NULL, ledger_id VARCHAR(64) NOT NULL,"
        " execution_id VARCHAR(64) NOT NULL, payment_id VARCHAR(64) NOT NULL,"
        " channel_transaction_id VARCHAR(64) NOT NULL,"
        " amount_minor BIGINT UNSIGNED NOT NULL, currency CHAR(3) NOT NULL,"
        " evidence_ref VARCHAR(128) NOT NULL, environment VARCHAR(32) NOT NULL,"
        " confirmed_at DATETIME(6) NOT NULL, created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, ledger_id),"
        " UNIQUE KEY uq_refund_ledger_channel (tenant_id, channel_transaction_id),"
        " KEY ix_refund_ledger_execution (tenant_id, execution_id),"
        " CONSTRAINT fk_refund_ledger_execution FOREIGN KEY (tenant_id, execution_id)"
        " REFERENCES refund_execution (tenant_id, execution_id),"
        " CONSTRAINT chk_refund_ledger_amount CHECK (amount_minor > 0)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS reconciliation_run ("
        " tenant_id VARCHAR(64) NOT NULL, run_id VARCHAR(64) NOT NULL,"
        " merchant_id VARCHAR(64) NOT NULL, currency CHAR(3) NOT NULL,"
        " window_start DATETIME(6) NOT NULL, window_end DATETIME(6) NOT NULL,"
        " status VARCHAR(16) NOT NULL,"
        " executed_count INT UNSIGNED NOT NULL, executed_minor BIGINT UNSIGNED NOT NULL,"
        " channel_count INT UNSIGNED NOT NULL, channel_minor BIGINT UNSIGNED NOT NULL,"
        " difference_count INT UNSIGNED NOT NULL,"
        " environment VARCHAR(32) NOT NULL, created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, run_id),"
        " CONSTRAINT chk_reconciliation_status CHECK (status IN ('balanced','difference'))"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS reconciliation_difference ("
        " tenant_id VARCHAR(64) NOT NULL, difference_id VARCHAR(64) NOT NULL,"
        " run_id VARCHAR(64) NULL,"
        " difference_type VARCHAR(32) NOT NULL,"
        " execution_id VARCHAR(64) NULL, channel_ref VARCHAR(64) NULL,"
        " amount_minor BIGINT UNSIGNED NOT NULL,"
        " detail JSON NOT NULL, environment VARCHAR(32) NOT NULL,"
        " created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, difference_id),"
        " KEY ix_reconciliation_difference_run (tenant_id, run_id),"
        " CONSTRAINT fk_reconciliation_difference_run FOREIGN KEY (tenant_id, run_id)"
        " REFERENCES reconciliation_run (tenant_id, run_id),"
        " CONSTRAINT chk_reconciliation_difference_type CHECK (difference_type IN"
        " ('channel_only','ledger_only','amount_mismatch','callback_mismatch'))"
        ")" + _SUFFIX,
        "ALTER TABLE mock_pay_refund_execution"
        " ADD COLUMN environment VARCHAR(32) NOT NULL DEFAULT 'simulation',"
        " ADD COLUMN created_at DATETIME(6) NULL",
    ]
