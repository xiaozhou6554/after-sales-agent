"""步骤25A：售后侧退货验收协同表；WMS 源记录仍归属独立模拟服务。"""

VERSION = "0019"
_SUFFIX = " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"


def statements() -> list[str]:
    return [
        "CREATE TABLE IF NOT EXISTS return_order ("
        " tenant_id VARCHAR(64) NOT NULL, return_id VARCHAR(64) NOT NULL,"
        " refund_request_id VARCHAR(64) NOT NULL, order_id VARCHAR(64) NOT NULL,"
        " customer_id VARCHAR(64) NOT NULL, created_by VARCHAR(64) NOT NULL,"
        " status VARCHAR(32) NOT NULL, revision BIGINT UNSIGNED NOT NULL DEFAULT 0,"
        " environment VARCHAR(32) NOT NULL,"
        " created_at DATETIME(6) NOT NULL, updated_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, return_id),"
        " UNIQUE KEY uq_return_request (tenant_id, refund_request_id),"
        " KEY ix_return_customer (tenant_id, customer_id, status),"
        " CONSTRAINT chk_return_status CHECK (status IN"
        " ('open','partially_received','received','partially_inspected','completed'))"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS return_line ("
        " tenant_id VARCHAR(64) NOT NULL, return_id VARCHAR(64) NOT NULL,"
        " line_id VARCHAR(64) NOT NULL, order_line_id VARCHAR(64) NOT NULL,"
        " rma_id VARCHAR(64) NOT NULL, approved_qty INT UNSIGNED NOT NULL,"
        " received_qty INT UNSIGNED NOT NULL DEFAULT 0,"
        " accepted_qty INT UNSIGNED NOT NULL DEFAULT 0,"
        " rejected_qty INT UNSIGNED NOT NULL DEFAULT 0,"
        " PRIMARY KEY (tenant_id, return_id, line_id),"
        " CONSTRAINT fk_return_line_order FOREIGN KEY (tenant_id, return_id)"
        " REFERENCES return_order (tenant_id, return_id),"
        " CONSTRAINT chk_return_line_qty CHECK (approved_qty > 0"
        " AND received_qty >= 0 AND accepted_qty >= 0 AND rejected_qty >= 0)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS warehouse_receipt ("
        " tenant_id VARCHAR(64) NOT NULL, operation_id VARCHAR(64) NOT NULL,"
        " return_id VARCHAR(64) NOT NULL, line_id VARCHAR(64) NOT NULL,"
        " received_qty INT UNSIGNED NOT NULL,"
        " source_record_id VARCHAR(128) NOT NULL, source_version VARCHAR(64) NOT NULL,"
        " actor_subject_id VARCHAR(64) NOT NULL, idempotency_key VARCHAR(64) NOT NULL,"
        " environment VARCHAR(32) NOT NULL, created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, operation_id, line_id),"
        " UNIQUE KEY uq_wms_receipt_source (tenant_id, source_record_id),"
        " CONSTRAINT fk_wms_receipt_return FOREIGN KEY (tenant_id, return_id, line_id)"
        " REFERENCES return_line (tenant_id, return_id, line_id),"
        " CONSTRAINT chk_wms_receipt_qty CHECK (received_qty > 0)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS warehouse_inspection ("
        " tenant_id VARCHAR(64) NOT NULL, operation_id VARCHAR(64) NOT NULL,"
        " return_id VARCHAR(64) NOT NULL, line_id VARCHAR(64) NOT NULL,"
        " accepted_qty INT UNSIGNED NOT NULL, rejected_qty INT UNSIGNED NOT NULL,"
        " reason_codes JSON NOT NULL,"
        " source_record_id VARCHAR(128) NOT NULL, source_version VARCHAR(64) NOT NULL,"
        " actor_subject_id VARCHAR(64) NOT NULL, idempotency_key VARCHAR(64) NOT NULL,"
        " environment VARCHAR(32) NOT NULL, created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, operation_id, line_id),"
        " UNIQUE KEY uq_wms_inspection_source (tenant_id, source_record_id),"
        " CONSTRAINT fk_wms_inspection_return FOREIGN KEY (tenant_id, return_id, line_id)"
        " REFERENCES return_line (tenant_id, return_id, line_id),"
        " CONSTRAINT chk_wms_inspection_qty CHECK (accepted_qty >= 0 AND rejected_qty >= 0)"
        ")" + _SUFFIX,
    ]
