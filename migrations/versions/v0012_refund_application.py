"""步骤25：退款报价、申请及逐行占用；不包含支付执行流水。"""

VERSION = "0012"
_SUFFIX = " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"


def statements() -> list[str]:
    return [
        "CREATE TABLE IF NOT EXISTS refund_quote ("
        " tenant_id VARCHAR(64) NOT NULL, quote_id VARCHAR(64) NOT NULL,"
        " order_id VARCHAR(64) NOT NULL, actor_subject_id VARCHAR(64) NOT NULL,"
        " customer_id VARCHAR(64) NOT NULL, reason_code VARCHAR(64) NOT NULL,"
        " eligibility VARCHAR(32) NOT NULL, amount_minor BIGINT UNSIGNED NOT NULL,"
        " goods_minor BIGINT UNSIGNED NOT NULL, shipping_minor BIGINT UNSIGNED NOT NULL,"
        " currency CHAR(3) NOT NULL, policy_id VARCHAR(64) NOT NULL,"
        " policy_version VARCHAR(64) NOT NULL, order_version VARCHAR(64) NOT NULL,"
        " payment_version VARCHAR(64) NOT NULL, expires_at DATETIME(6) NOT NULL,"
        " created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, quote_id),"
        " KEY ix_refund_quote_order (tenant_id, order_id, expires_at),"
        " CONSTRAINT chk_refund_quote_amount"
        " CHECK (amount_minor > 0 AND amount_minor = goods_minor + shipping_minor)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS refund_request ("
        " tenant_id VARCHAR(64) NOT NULL, refund_request_id VARCHAR(64) NOT NULL,"
        " quote_id VARCHAR(64) NOT NULL, order_id VARCHAR(64) NOT NULL,"
        " actor_subject_id VARCHAR(64) NOT NULL, customer_id VARCHAR(64) NOT NULL,"
        " confirmation_id VARCHAR(64) NOT NULL, idempotency_key VARCHAR(64) NOT NULL,"
        " reason_code VARCHAR(64) NOT NULL, eligibility VARCHAR(32) NOT NULL,"
        " review_status VARCHAR(32) NOT NULL, review_revision BIGINT UNSIGNED NOT NULL DEFAULT 0,"
        " amount_minor BIGINT UNSIGNED NOT NULL, goods_minor BIGINT UNSIGNED NOT NULL,"
        " shipping_minor BIGINT UNSIGNED NOT NULL, currency CHAR(3) NOT NULL,"
        " policy_id VARCHAR(64) NOT NULL, policy_version VARCHAR(64) NOT NULL,"
        " order_version VARCHAR(64) NOT NULL, payment_version VARCHAR(64) NOT NULL,"
        " reviewer_subject_id VARCHAR(64) NULL, review_reason_code VARCHAR(64) NULL,"
        " created_at DATETIME(6) NOT NULL, updated_at DATETIME(6) NOT NULL,"
        " active_order_id VARCHAR(64) GENERATED ALWAYS AS"
        " (CASE WHEN review_status IN ('pending_review','reviewing','approved')"
        " THEN order_id ELSE NULL END) STORED,"
        " PRIMARY KEY (tenant_id, refund_request_id),"
        " UNIQUE KEY uq_refund_request_quote (tenant_id, quote_id),"
        " UNIQUE KEY uq_refund_request_idem (tenant_id, actor_subject_id, idempotency_key),"
        " UNIQUE KEY uq_refund_active_order (tenant_id, active_order_id),"
        " KEY ix_refund_request_owner (tenant_id, customer_id, order_id),"
        " CONSTRAINT chk_refund_request_amount"
        " CHECK (amount_minor > 0 AND amount_minor = goods_minor + shipping_minor),"
        " CONSTRAINT chk_refund_review_status"
        " CHECK (review_status IN ('pending_review','reviewing','approved','rejected'))"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS refund_request_line ("
        " tenant_id VARCHAR(64) NOT NULL, refund_request_id VARCHAR(64) NOT NULL,"
        " line_id VARCHAR(64) NOT NULL, quantity INT UNSIGNED NOT NULL,"
        " goods_minor BIGINT UNSIGNED NOT NULL, shipping_minor BIGINT UNSIGNED NOT NULL,"
        " PRIMARY KEY (tenant_id, refund_request_id, line_id),"
        " CONSTRAINT fk_refund_line_request FOREIGN KEY (tenant_id, refund_request_id)"
        " REFERENCES refund_request (tenant_id, refund_request_id),"
        " CONSTRAINT chk_refund_line_amount CHECK (quantity > 0)"
        ")" + _SUFFIX,
    ]
