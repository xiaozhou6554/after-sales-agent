"""步骤25C：本体发布指针与分析只读投影（事实/隔离/快照）；源事实仍归属各模拟系统。"""

VERSION = "0021"
_SUFFIX = " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"


def statements() -> list[str]:
    return [
        "CREATE TABLE IF NOT EXISTS ontology_release ("
        " tenant_id VARCHAR(64) NOT NULL, release_id VARCHAR(64) NOT NULL,"
        " schema_version VARCHAR(32) NOT NULL,"
        " mapping_version INT UNSIGNED NOT NULL, metric_version INT UNSIGNED NOT NULL,"
        " manifest_digest CHAR(64) NOT NULL, manifest_json JSON NOT NULL,"
        " status VARCHAR(16) NOT NULL, revision BIGINT UNSIGNED NOT NULL,"
        " effective_at DATETIME(6) NULL,"
        " created_at DATETIME(6) NOT NULL, activated_at DATETIME(6) NULL,"
        " PRIMARY KEY (tenant_id, release_id),"
        " KEY ix_ontology_release_status (tenant_id, status),"
        " CONSTRAINT chk_ontology_release_status CHECK (status IN"
        " ('candidate','validated','active','retired')),"
        " CONSTRAINT chk_ontology_release_digest CHECK (CHAR_LENGTH(manifest_digest) = 64)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS analytics_fact ("
        " tenant_id VARCHAR(64) NOT NULL, fact_id VARCHAR(64) NOT NULL,"
        " projection_version VARCHAR(32) NOT NULL, fact_type VARCHAR(32) NOT NULL,"
        " source_system VARCHAR(16) NOT NULL, source_record_id VARCHAR(128) NOT NULL,"
        " source_version VARCHAR(32) NULL, event_time DATETIME(6) NULL,"
        " canonical_product_id VARCHAR(64) NULL, mapping_status VARCHAR(16) NOT NULL,"
        " mapping_version INT UNSIGNED NULL, cohort_id VARCHAR(32) NULL,"
        " quantity BIGINT NULL, goods_minor BIGINT NULL, shipping_minor BIGINT NULL,"
        " dedup_key VARCHAR(191) NOT NULL,"
        " revision INT UNSIGNED NOT NULL, superseded_by VARCHAR(64) NULL,"
        " payload JSON NOT NULL, evidence JSON NULL,"
        " environment VARCHAR(32) NOT NULL, created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, fact_id),"
        " UNIQUE KEY uq_analytics_fact_dedup (tenant_id, projection_version,"
        " fact_type, dedup_key),"
        " KEY ix_analytics_fact_lookup (tenant_id, projection_version, fact_type,"
        " cohort_id),"
        " CONSTRAINT chk_analytics_fact_revision CHECK (revision >= 1)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS analytics_quarantine ("
        " tenant_id VARCHAR(64) NOT NULL, quarantine_id VARCHAR(64) NOT NULL,"
        " projection_version VARCHAR(32) NOT NULL, reason VARCHAR(32) NOT NULL,"
        " source_system VARCHAR(16) NOT NULL, source_record_id VARCHAR(128) NOT NULL,"
        " detail JSON NOT NULL, environment VARCHAR(32) NOT NULL,"
        " created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, quarantine_id),"
        " UNIQUE KEY uq_analytics_quarantine (tenant_id, projection_version, reason,"
        " source_system, source_record_id),"
        " CONSTRAINT chk_analytics_quarantine_reason CHECK (reason IN"
        " ('missing_mapping','ambiguous_mapping','unknown_state',"
        " 'conservation_mismatch','reconciliation_difference','watermark_lag',"
        " 'ambiguous_product_attribution'))"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS analytics_metric_snapshot ("
        " tenant_id VARCHAR(64) NOT NULL, snapshot_id VARCHAR(64) NOT NULL,"
        " projection_version VARCHAR(32) NOT NULL,"
        " metric_id VARCHAR(64) NOT NULL, metric_version INT UNSIGNED NOT NULL,"
        " product_id VARCHAR(64) NOT NULL, cohort VARCHAR(32) NOT NULL,"
        " window_start DATE NOT NULL, window_end DATE NOT NULL,"
        " numerator BIGINT UNSIGNED NOT NULL, denominator BIGINT UNSIGNED NOT NULL,"
        " rate DECIMAL(14,8) NULL, min_sample INT UNSIGNED NOT NULL,"
        " quality VARCHAR(32) NOT NULL, excluded_reasons JSON NOT NULL,"
        " source_watermarks JSON NOT NULL, reconciliation_run_id VARCHAR(64) NULL,"
        " as_of DATETIME(6) NOT NULL, environment VARCHAR(32) NOT NULL,"
        " created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, snapshot_id),"
        " UNIQUE KEY uq_analytics_snapshot (tenant_id, projection_version, metric_id,"
        " product_id, cohort),"
        " CONSTRAINT chk_analytics_snapshot_quality CHECK (quality IN"
        " ('complete','insufficient_sample','zero_denominator','immature',"
        " 'watermark_lag','reconciliation_difference','quarantined'))"
        ")" + _SUFFIX,
    ]
