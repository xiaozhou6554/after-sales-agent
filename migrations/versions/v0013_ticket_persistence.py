"""Step 27 ticket-owned tables; replayable after interrupted MySQL DDL."""

VERSION = "0013"
_SUFFIX = " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"


def statements() -> list[str]:
    return [
        "CREATE TABLE IF NOT EXISTS ticket ("
        " tenant_id VARCHAR(64) NOT NULL, ticket_id VARCHAR(64) NOT NULL,"
        " customer_id VARCHAR(64) NOT NULL, created_by VARCHAR(64) NOT NULL,"
        " title VARCHAR(255) NOT NULL, description_masked TEXT NOT NULL,"
        " priority VARCHAR(32) NOT NULL, status VARCHAR(32) NOT NULL,"
        " assigned_to VARCHAR(64) NULL, revision BIGINT UNSIGNED NOT NULL,"
        " context_snapshot JSON NOT NULL, thread_id VARCHAR(64) NOT NULL,"
        " correlation_id VARCHAR(64) NOT NULL, trace_id VARCHAR(64) NOT NULL,"
        " created_at DATETIME(6) NOT NULL, updated_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, ticket_id),"
        " KEY ix_ticket_customer_status (tenant_id, customer_id, status, created_at),"
        " KEY ix_ticket_assignee_status (tenant_id, assigned_to, status)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS ticket_message ("
        " tenant_id VARCHAR(64) NOT NULL, message_id VARCHAR(64) NOT NULL,"
        " ticket_id VARCHAR(64) NOT NULL, author_subject_id VARCHAR(64) NOT NULL,"
        " content_masked TEXT NOT NULL, visibility VARCHAR(32) NOT NULL,"
        " created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, message_id),"
        " KEY ix_ticket_message_order (tenant_id, ticket_id, created_at),"
        " CONSTRAINT fk_ticket_message_ticket FOREIGN KEY (tenant_id, ticket_id)"
        " REFERENCES ticket (tenant_id, ticket_id)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS ticket_write_confirmation ("
        " tenant_id VARCHAR(64) NOT NULL, confirmation_id VARCHAR(64) NOT NULL,"
        " customer_id VARCHAR(64) NOT NULL, actor_subject_id VARCHAR(64) NOT NULL,"
        " operation_type VARCHAR(32) NOT NULL, target_id VARCHAR(64) NOT NULL,"
        " payload_masked JSON NOT NULL, payload_digest CHAR(64) NOT NULL,"
        " expected_revision BIGINT UNSIGNED NULL, expires_at DATETIME(6) NOT NULL,"
        " consumed_at DATETIME(6) NULL, created_at DATETIME(6) NOT NULL,"
        " updated_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, confirmation_id),"
        " KEY ix_ticket_confirm_actor (tenant_id, actor_subject_id, target_id)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS human_handoff ("
        " tenant_id VARCHAR(64) NOT NULL, handoff_id VARCHAR(64) NOT NULL,"
        " ticket_id VARCHAR(64) NULL, customer_id VARCHAR(64) NOT NULL,"
        " requested_by VARCHAR(64) NOT NULL, reason_code VARCHAR(64) NOT NULL,"
        " summary_masked TEXT NOT NULL, context_snapshot JSON NOT NULL,"
        " status VARCHAR(32) NOT NULL, assigned_to VARCHAR(64) NULL,"
        " revision BIGINT UNSIGNED NOT NULL, thread_id VARCHAR(64) NOT NULL,"
        " correlation_id VARCHAR(64) NOT NULL, created_at DATETIME(6) NOT NULL,"
        " updated_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, handoff_id),"
        " KEY ix_handoff_customer_status (tenant_id, customer_id, status),"
        " KEY ix_handoff_queue (tenant_id, status, created_at),"
        " CONSTRAINT fk_handoff_ticket FOREIGN KEY (tenant_id, ticket_id)"
        " REFERENCES ticket (tenant_id, ticket_id)"
        ")" + _SUFFIX,
        "CREATE TABLE IF NOT EXISTS ticket_write_idempotency ("
        " tenant_id VARCHAR(64) NOT NULL, actor_subject_id VARCHAR(64) NOT NULL,"
        " operation_type VARCHAR(32) NOT NULL, idempotency_key VARCHAR(64) NOT NULL,"
        " request_digest CHAR(64) NOT NULL, ticket_id VARCHAR(64) NOT NULL,"
        " result_revision BIGINT UNSIGNED NOT NULL, created_at DATETIME(6) NOT NULL,"
        " PRIMARY KEY (tenant_id, actor_subject_id, operation_type, idempotency_key),"
        " KEY ix_ticket_idem_resource (tenant_id, ticket_id),"
        " CONSTRAINT fk_ticket_idem_ticket FOREIGN KEY (tenant_id, ticket_id)"
        " REFERENCES ticket (tenant_id, ticket_id)"
        ")" + _SUFFIX,
    ]
